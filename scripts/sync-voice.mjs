// Copies the voice brain (src/voice/{bn,lexicon,brain}.js) into the voice-agent service as TypeScript-compatible modules,
// so the phone/Soniox pipeline and the in-browser assistant give the same answers from the same snapshot.
//   npm run sync:voice
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'services/voice-agent/lib/agent/field/shared');
mkdirSync(out, { recursive: true });
for (const f of ['bn', 'lexicon', 'brain']) {
  let src = readFileSync(join(root, 'src/voice', `${f}.js`), 'utf8').replace(/\r\n/g, '\n');
  src = src.replace(/from '\.\/(\w+)\.js'/g, "from './$1'");
  writeFileSync(join(out, `${f}.ts`), `// @ts-nocheck\n// GENERATED by \`npm run sync:voice\` from src/voice/${f}.js. Edit the source, not this copy.\n${src}`);
  console.log('synced', f);
}
